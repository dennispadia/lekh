const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('lekh', {
  open: (recentPath) => ipcRenderer.invoke('document:open', recentPath),
  openPending: () => ipcRenderer.invoke('document:open-pending'),
  save: (id, content, saveAs) => ipcRenderer.invoke('document:save', id, content, saveAs),
  newDocument: () => ipcRenderer.invoke('document:new'),
  closeDocument: (id) => ipcRenderer.invoke('document:release', id),
  allowImageFolder: (id) => ipcRenderer.invoke('images:allow-folder', id),
  revokeImageFolder: (id) => ipcRenderer.invoke('images:revoke-folder', id),
  allowIncludeFolder: (id) => ipcRenderer.invoke('includes:allow-folder', id),
  revokeIncludeFolder: (id) => ipcRenderer.invoke('includes:revoke-folder', id),
  previewIncludes: (id, content) => ipcRenderer.invoke('includes:preview', id, content),
  includesRequireInteractiveExport: (id, content) => ipcRenderer.invoke('includes:interactive', id, content),
  checkLearnPaths: (id, paths) => ipcRenderer.invoke('learn:check-paths', id, paths),
  relationshipWorkspace: (id, revoke) => ipcRenderer.invoke('relationships:workspace', id, revoke),
  includeRelationships: (id, content, source, refresh) => ipcRenderer.invoke('relationships:query', id, content, source, refresh),
  openRelationship: (id, file) => ipcRenderer.invoke('relationships:open', id, file),
  onIncludeAccessChanged: (listener) => ipcRenderer.on('includes:access-changed', (_event, id) => listener(id)),
  prepareVariantConfiguration: (id, content) => ipcRenderer.invoke('variant-config:prepare', id, content),
  chooseVariantConfigFile: (id) => ipcRenderer.invoke('variant-config:choose-file', id),
  createVariantGroup: (id, token, group, content) => ipcRenderer.invoke('variant-config:create-group', id, token, group, content),
  exportDocument: (id, content, format) => ipcRenderer.invoke('document:export', id, content, format),
  insertImage: () => ipcRenderer.invoke('document:image'),
  storeImage: (id, source, storage) => ipcRenderer.invoke('document:store-image', id, source, storage),
  recent: () => ipcRenderer.invoke('document:recent'),
  clearRecent: () => ipcRenderer.invoke('document:clear-recent'),
  zoom: (command) => ipcRenderer.invoke('app:zoom', command),
  setTheme: (theme) => ipcRenderer.invoke('app:theme', theme),
  confirmUnsaved: (name) => ipcRenderer.invoke('document:confirm', name),
  setEditorContext: (context) => ipcRenderer.send('editor:context', context),
  onContextMenu: (listener) => ipcRenderer.on('editor:context-menu', (_event, menu) => listener(menu)),
  contextMenuCommand: (id, command) => ipcRenderer.invoke('editor:context-menu-command', id, command),
  readClipboard: () => ipcRenderer.invoke('editor:clipboard-read'),
  paste: () => ipcRenderer.send('editor:paste'),
  readClipboardImage: () => ipcRenderer.invoke('editor:clipboard-image'),
  copyImage: (id, source) => ipcRenderer.invoke('editor:copy-image', id, source),
  writeClipboard: (text) => ipcRenderer.invoke('editor:clipboard-write', text),
  setDirty: (dirty) => ipcRenderer.send('document:dirty', dirty),
  close: () => ipcRenderer.send('document:close'),
  openExternal: (url) => ipcRenderer.invoke('app:external', url),
  onAction: (listener) => ipcRenderer.on('app:action', (_event, action) => listener(action)),
});
